import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

/**
 * The panel runs in its own sandboxed renderer, where neither Obsidian nor its
 * CodeMirror exists. So its editor is bundled separately - CodeMirror
 * included - and handed to main.js as the text of `virtual:panel-editor`.
 */
const panelEditor = {
	name: 'panel-editor',
	setup(build) {
		build.onResolve({ filter: /^virtual:panel-editor$/ }, (args) => ({ path: args.path, namespace: 'panel-editor' }));
		build.onLoad({ filter: /.*/, namespace: 'panel-editor' }, async () => {
			const result = await esbuild.build({
				entryPoints: ['src/panel-editor/index.ts'],
				bundle: true,
				write: false,
				format: 'iife',
				target: 'es2021',
				minify: prod,
				metafile: true,
				logLevel: 'silent',
			});
			return {
				contents: result.outputFiles[0].text,
				loader: 'text',
				watchFiles: Object.keys(result.metafile.inputs),
			};
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [panelEditor],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
